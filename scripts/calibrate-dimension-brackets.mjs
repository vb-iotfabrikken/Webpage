/**
 * Detect bracket centres from dimension source PNGs and emit calibration data.
 *
 * Run: node scripts/calibrate-dimension-brackets.mjs [--preview]
 */
import { access, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { detectDimensionBracketSlots } from "./lib/detect-dimension-brackets.mjs";
import { dimensionImageMappings, dimensionSourceDir } from "./lib/dimension-image-mappings.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = join(root, dimensionSourceDir);
const outFile = join(root, "src/data/dimensionBracketCalibration.ts");
const preview = process.argv.includes("--preview");

/** @type {Record<string, Record<string, { x: number; y: number }>>} */
const calibration = {};

let entryCount = 0;

for (const { source, targets } of dimensionImageMappings) {
  const sourcePath = join(sourceDir, source);

  try {
    await access(sourcePath);
  } catch {
    console.warn(`Skip calibration (missing source): ${source}`);
    continue;
  }

  const { slots } = await detectDimensionBracketSlots(sourcePath);

  if (!slots.h && !slots.w) {
    console.warn(`Skip calibration (no brackets detected): ${source}`);
    continue;
  }

  for (const target of targets) {
    /** @type {Record<string, { x: number; y: number }>} */
    const entry = {};
    if (slots.h) entry.h = { x: slots.h.x, y: slots.h.y };
    if (slots.w) entry.w = { x: slots.w.x, y: slots.w.y };
    if (slots.static) entry.static = { x: slots.static.x, y: slots.static.y };
    calibration[target] = entry;
    entryCount++;
    console.log(`✓ ${target} ← ${source}`);
  }
}

const ts = `/** Generated by scripts/calibrate-dimension-brackets.mjs — do not edit. */
export type DimensionBracketSlot = "h" | "w" | "static";

export type DimensionBracketCoords = { x: number; y: number };

export const dimensionBracketCalibration = ${JSON.stringify(calibration, null, 2)} as const satisfies Record<
  string,
  Partial<Record<DimensionBracketSlot, DimensionBracketCoords>>
>;
`;

await writeFile(outFile, ts);
console.log(`\nWrote ${entryCount} entries to src/data/dimensionBracketCalibration.ts`);

if (preview) {
  const { spawn } = await import("node:child_process");
  await new Promise((resolve, reject) => {
    const child = spawn("node", ["scripts/mockup-dimension-calibration.mjs"], {
      cwd: root,
      stdio: "inherit",
      shell: true,
    });
    child.on("exit", (code) => (code === 0 ? resolve(undefined) : reject(new Error(`preview exited ${code}`))));
  });
}
